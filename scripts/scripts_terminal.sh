#!/usr/bin/env bash
r(){ echo "\$ $*"; eval "$@" 2>&1; echo; }
cd ~
r 'pwd'
r 'mkdir -p ~/codyssey/practice'
r 'cd ~/codyssey/practice'
r 'pwd'
r 'touch empty.txt'
r 'echo "hello codyssey" > hello.txt'
r 'mkdir -p dir_a/sub'
r 'ls -la'
r 'cat hello.txt'
r 'cp hello.txt dir_a/hello_copy.txt'
r 'mv dir_a/hello_copy.txt dir_a/sub/renamed.txt'
r 'ls -laR dir_a'
r 'cd dir_a/sub && pwd && cd ../..'
r 'cat ./dir_a/sub/renamed.txt'
r 'cat ~/codyssey/practice/dir_a/sub/renamed.txt'
r 'echo ".secret" > .hidden_config'
r 'ls -a'
r 'ls -la'
r 'wc -c empty.txt'
r 'rm dir_a/sub/renamed.txt'
r 'rm -r dir_a'
r 'ls -la'
